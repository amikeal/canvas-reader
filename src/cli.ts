// Command-line converter (for bulk use and testing). Runs the same core as the
// browser app, with jsdom supplying DOMParser/DOMPurify's window.
//
//   tsx src/cli.ts course.imscc out.zip            # write a ZIP
//   tsx src/cli.ts course.imscc out-dir/           # write an unpacked site
//   options: --answers  --no-unpublished

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { JSDOM } from 'jsdom';

const dom = new JSDOM('');
Object.assign(globalThis, { window: dom.window, DOMParser: dom.window.DOMParser });

const { convert, zipSite } = await import('./core/index');

const args = process.argv.slice(2);
const flags = new Set(args.filter((a) => a.startsWith('--')));
const [input, output] = args.filter((a) => !a.startsWith('--'));
if (!input || !output) {
  console.error('usage: tsx src/cli.ts <course.imscc> <out.zip | out-dir/> [--answers] [--no-unpublished]');
  process.exit(2);
}

const t0 = performance.now();
const { course, site, warnings } = await convert(new Uint8Array(await readFile(input)), {
  includeAnswers: flags.has('--answers'),
  includeUnpublished: !flags.has('--no-unpublished'),
});

if (output.endsWith('.zip')) {
  await writeFile(output, await zipSite(site));
} else {
  const root = resolve(output);
  for (const [path, bytes] of site.files) {
    const dest = resolve(root, path);
    // Paths are generated by us, but never trust that: refuse anything outside root.
    if (!dest.startsWith(root + sep)) throw new Error(`refusing to write outside output dir: ${path}`);
    await mkdir(dirname(dest), { recursive: true });
    await writeFile(dest, bytes);
  }
}

console.log(`${course.title}`);
console.log(Object.entries(site.stats).map(([k, v]) => `${k}=${v}`).join(' '));
for (const w of warnings) console.log(`warning: ${w}`);
console.log(`wrote ${output} in ${Math.round(performance.now() - t0)} ms`);
